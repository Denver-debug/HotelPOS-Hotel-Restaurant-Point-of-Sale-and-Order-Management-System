-- Shifts, orders, discounts, payments, guest room charges, refunds and receipts.
-- Financial rows are never deleted: corrections are made with voids, refunds and reversals.

CREATE TABLE shifts (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  shift_number VARCHAR(30) NOT NULL,
  user_id INT UNSIGNED NOT NULL,
  outlet_id INT UNSIGNED NOT NULL,
  status ENUM('OPEN','CLOSED','RECONCILED') NOT NULL DEFAULT 'OPEN',
  opened_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  closed_at DATETIME NULL,
  opening_cash DECIMAL(12,2) NOT NULL DEFAULT 0,
  expected_cash DECIMAL(12,2) NULL,
  actual_cash DECIMAL(12,2) NULL,
  cash_variance DECIMAL(12,2) NULL,
  opening_notes VARCHAR(255) NULL,
  closing_notes VARCHAR(255) NULL,
  closed_by INT UNSIGNED NULL,
  reconciled_by INT UNSIGNED NULL,
  reconciled_at DATETIME NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  open_user_key INT UNSIGNED GENERATED ALWAYS AS (IF(status = 'OPEN', user_id, NULL)) STORED,
  UNIQUE KEY uq_shifts_number (shift_number),
  UNIQUE KEY uq_shifts_one_open_per_user (open_user_key),
  KEY idx_shifts_outlet (outlet_id, opened_at),
  KEY idx_shifts_user (user_id, opened_at),
  KEY idx_shifts_status (status),
  CONSTRAINT fk_shifts_user FOREIGN KEY (user_id) REFERENCES users (id),
  CONSTRAINT fk_shifts_outlet FOREIGN KEY (outlet_id) REFERENCES outlets (id),
  CONSTRAINT fk_shifts_closed_by FOREIGN KEY (closed_by) REFERENCES users (id),
  CONSTRAINT fk_shifts_reconciled_by FOREIGN KEY (reconciled_by) REFERENCES users (id),
  CONSTRAINT chk_shifts_opening_cash CHECK (opening_cash >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE orders (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  order_number VARCHAR(30) NOT NULL,
  outlet_id INT UNSIGNED NOT NULL,
  shift_id INT UNSIGNED NULL,
  created_by INT UNSIGNED NOT NULL,
  order_type ENUM('DINE_IN','TAKEOUT','ROOM_SERVICE','MINIBAR','SPA','OTHER') NOT NULL,
  settlement_type ENUM('DIRECT_PAYMENT','ROOM_CHARGE') NULL,
  status ENUM('OPEN','IN_PROGRESS','AWAITING_SETTLEMENT','SETTLING','CHARGE_FAILED','COMPLETED','VOIDED','PARTIALLY_REFUNDED','REFUNDED') NOT NULL DEFAULT 'OPEN',
  table_or_location VARCHAR(60) NULL,
  guest_count SMALLINT UNSIGNED NULL,
  notes VARCHAR(500) NULL,
  service_charge_rate DECIMAL(5,2) NOT NULL DEFAULT 0 COMMENT 'snapshot of outlet rate, percent',
  subtotal DECIMAL(12,2) NOT NULL DEFAULT 0 COMMENT 'gross item amounts before discounts',
  discount_amount DECIMAL(12,2) NOT NULL DEFAULT 0,
  tax_amount DECIMAL(12,2) NOT NULL DEFAULT 0,
  service_charge_amount DECIMAL(12,2) NOT NULL DEFAULT 0,
  total_amount DECIMAL(12,2) NOT NULL DEFAULT 0,
  amount_paid DECIMAL(12,2) NOT NULL DEFAULT 0,
  amount_refunded DECIMAL(12,2) NOT NULL DEFAULT 0,
  void_reason VARCHAR(255) NULL,
  void_requested_by INT UNSIGNED NULL,
  voided_by INT UNSIGNED NULL,
  voided_at DATETIME NULL,
  completed_by INT UNSIGNED NULL,
  completed_at DATETIME NULL,
  version INT UNSIGNED NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_orders_number (order_number),
  KEY idx_orders_outlet (outlet_id, created_at),
  KEY idx_orders_status (status, created_at),
  KEY idx_orders_shift (shift_id),
  KEY idx_orders_created_by (created_by, created_at),
  KEY idx_orders_completed (completed_at),
  CONSTRAINT fk_orders_outlet FOREIGN KEY (outlet_id) REFERENCES outlets (id),
  CONSTRAINT fk_orders_shift FOREIGN KEY (shift_id) REFERENCES shifts (id),
  CONSTRAINT fk_orders_created_by FOREIGN KEY (created_by) REFERENCES users (id),
  CONSTRAINT fk_orders_void_requested_by FOREIGN KEY (void_requested_by) REFERENCES users (id),
  CONSTRAINT fk_orders_voided_by FOREIGN KEY (voided_by) REFERENCES users (id),
  CONSTRAINT fk_orders_completed_by FOREIGN KEY (completed_by) REFERENCES users (id),
  CONSTRAINT chk_orders_amounts CHECK (total_amount >= 0 AND amount_paid >= 0 AND amount_refunded >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Product details are snapshotted so later catalog changes never alter historical orders.
CREATE TABLE order_items (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  order_id BIGINT UNSIGNED NOT NULL,
  product_id INT UNSIGNED NOT NULL,
  product_code VARCHAR(40) NOT NULL,
  product_name VARCHAR(120) NOT NULL,
  item_type ENUM('PRODUCT','SERVICE') NOT NULL,
  unit VARCHAR(20) NOT NULL,
  quantity DECIMAL(10,3) NOT NULL,
  unit_price DECIMAL(12,2) NOT NULL,
  gross_amount DECIMAL(12,2) NOT NULL COMMENT 'unit_price x quantity',
  discount_amount DECIMAL(12,2) NOT NULL DEFAULT 0,
  tax_rate DECIMAL(7,4) NOT NULL DEFAULT 0,
  tax_inclusive TINYINT(1) NOT NULL DEFAULT 1,
  tax_amount DECIMAL(12,2) NOT NULL DEFAULT 0,
  net_amount DECIMAL(12,2) NOT NULL DEFAULT 0 COMMENT 'after discount, excluding tax',
  line_total DECIMAL(12,2) NOT NULL DEFAULT 0 COMMENT 'amount charged for the line (excl. service charge)',
  quantity_refunded DECIMAL(10,3) NOT NULL DEFAULT 0,
  notes VARCHAR(255) NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY idx_order_items_order (order_id),
  KEY idx_order_items_product (product_id),
  CONSTRAINT fk_order_items_order FOREIGN KEY (order_id) REFERENCES orders (id),
  CONSTRAINT fk_order_items_product FOREIGN KEY (product_id) REFERENCES products (id),
  CONSTRAINT chk_order_items_qty CHECK (quantity > 0 AND quantity_refunded >= 0 AND quantity_refunded <= quantity)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE discounts (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  code VARCHAR(30) NOT NULL,
  name VARCHAR(100) NOT NULL,
  description VARCHAR(255) NULL,
  discount_type ENUM('PERCENTAGE','FIXED') NOT NULL,
  value DECIMAL(12,2) NOT NULL,
  scope ENUM('ORDER','ITEM') NOT NULL DEFAULT 'ORDER',
  requires_authorization TINYINT(1) NOT NULL DEFAULT 0,
  min_order_amount DECIMAL(12,2) NULL,
  valid_from DATETIME NULL,
  valid_to DATETIME NULL,
  max_uses INT UNSIGNED NULL,
  times_used INT UNSIGNED NOT NULL DEFAULT 0,
  status ENUM('ACTIVE','INACTIVE','ARCHIVED') NOT NULL DEFAULT 'ACTIVE',
  created_by INT UNSIGNED NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_discounts_code (code),
  KEY idx_discounts_status (status, valid_from, valid_to),
  CONSTRAINT fk_discounts_user FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT chk_discounts_value CHECK (value > 0 AND (discount_type = 'FIXED' OR value <= 100))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Applicability: no rows = applies to all products / all outlets.
CREATE TABLE discount_products (
  discount_id INT UNSIGNED NOT NULL,
  product_id INT UNSIGNED NOT NULL,
  PRIMARY KEY (discount_id, product_id),
  CONSTRAINT fk_discount_products_discount FOREIGN KEY (discount_id) REFERENCES discounts (id) ON DELETE CASCADE,
  CONSTRAINT fk_discount_products_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE discount_outlets (
  discount_id INT UNSIGNED NOT NULL,
  outlet_id INT UNSIGNED NOT NULL,
  PRIMARY KEY (discount_id, outlet_id),
  CONSTRAINT fk_discount_outlets_discount FOREIGN KEY (discount_id) REFERENCES discounts (id) ON DELETE CASCADE,
  CONSTRAINT fk_discount_outlets_outlet FOREIGN KEY (outlet_id) REFERENCES outlets (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Discount usage with snapshots of the discount definition at the time it was applied.
CREATE TABLE order_discounts (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  order_id BIGINT UNSIGNED NOT NULL,
  order_item_id BIGINT UNSIGNED NULL,
  discount_id INT UNSIGNED NOT NULL,
  discount_code VARCHAR(30) NOT NULL,
  discount_name VARCHAR(100) NOT NULL,
  discount_type ENUM('PERCENTAGE','FIXED') NOT NULL,
  discount_value DECIMAL(12,2) NOT NULL,
  amount DECIMAL(12,2) NOT NULL DEFAULT 0,
  applied_by INT UNSIGNED NOT NULL,
  authorized_by INT UNSIGNED NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY idx_order_discounts_order (order_id),
  KEY idx_order_discounts_discount (discount_id, created_at),
  CONSTRAINT fk_order_discounts_order FOREIGN KEY (order_id) REFERENCES orders (id),
  CONSTRAINT fk_order_discounts_item FOREIGN KEY (order_item_id) REFERENCES order_items (id) ON DELETE CASCADE,
  CONSTRAINT fk_order_discounts_discount FOREIGN KEY (discount_id) REFERENCES discounts (id),
  CONSTRAINT fk_order_discounts_applied_by FOREIGN KEY (applied_by) REFERENCES users (id),
  CONSTRAINT fk_order_discounts_authorized_by FOREIGN KEY (authorized_by) REFERENCES users (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE payment_methods (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  code VARCHAR(30) NOT NULL,
  name VARCHAR(60) NOT NULL,
  is_cash TINYINT(1) NOT NULL DEFAULT 0,
  uses_gateway TINYINT(1) NOT NULL DEFAULT 0,
  requires_reference TINYINT(1) NOT NULL DEFAULT 0,
  sort_order INT NOT NULL DEFAULT 0,
  status ENUM('ACTIVE','INACTIVE') NOT NULL DEFAULT 'ACTIVE',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_payment_methods_code (code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE payments (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  payment_number VARCHAR(30) NOT NULL,
  order_id BIGINT UNSIGNED NOT NULL,
  shift_id INT UNSIGNED NULL,
  payment_method_id INT UNSIGNED NOT NULL,
  amount DECIMAL(12,2) NOT NULL,
  tendered_amount DECIMAL(12,2) NULL,
  change_amount DECIMAL(12,2) NOT NULL DEFAULT 0,
  refunded_amount DECIMAL(12,2) NOT NULL DEFAULT 0,
  reference VARCHAR(100) NULL,
  status ENUM('PENDING','AUTHORIZED','CAPTURED','FAILED','VOIDED','REFUNDED','PARTIALLY_REFUNDED') NOT NULL DEFAULT 'PENDING',
  gateway VARCHAR(40) NULL,
  external_transaction_id VARCHAR(100) NULL,
  idempotency_key VARCHAR(100) NOT NULL,
  failure_reason VARCHAR(255) NULL,
  is_mock TINYINT(1) NOT NULL DEFAULT 0,
  processed_by INT UNSIGNED NOT NULL,
  captured_at DATETIME NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_payments_number (payment_number),
  UNIQUE KEY uq_payments_idempotency (idempotency_key),
  KEY idx_payments_order (order_id),
  KEY idx_payments_shift (shift_id, status),
  KEY idx_payments_method (payment_method_id, created_at),
  KEY idx_payments_created (created_at),
  CONSTRAINT fk_payments_order FOREIGN KEY (order_id) REFERENCES orders (id),
  CONSTRAINT fk_payments_shift FOREIGN KEY (shift_id) REFERENCES shifts (id),
  CONSTRAINT fk_payments_method FOREIGN KEY (payment_method_id) REFERENCES payment_methods (id),
  CONSTRAINT fk_payments_processed_by FOREIGN KEY (processed_by) REFERENCES users (id),
  CONSTRAINT chk_payments_amount CHECK (amount > 0 AND refunded_amount >= 0 AND refunded_amount <= amount)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Room charges posted to PMS guest folios. Only external PMS identifiers are stored;
-- the room number is the lookup input, never a guest identifier.
CREATE TABLE guest_charges (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  charge_number VARCHAR(30) NOT NULL,
  order_id BIGINT UNSIGNED NOT NULL,
  room_number VARCHAR(20) NOT NULL,
  external_guest_id VARCHAR(60) NOT NULL,
  external_room_id VARCHAR(60) NOT NULL,
  external_folio_id VARCHAR(60) NOT NULL,
  amount DECIMAL(12,2) NOT NULL,
  reversed_amount DECIMAL(12,2) NOT NULL DEFAULT 0,
  status ENUM('PENDING','POSTED','FAILED','UNKNOWN','REVERSED','PARTIALLY_REVERSED') NOT NULL DEFAULT 'PENDING',
  idempotency_key VARCHAR(100) NOT NULL,
  pms_transaction_id VARCHAR(100) NULL,
  attempts TINYINT UNSIGNED NOT NULL DEFAULT 0,
  last_error VARCHAR(500) NULL,
  is_mock TINYINT(1) NOT NULL DEFAULT 0,
  requested_by INT UNSIGNED NOT NULL,
  posted_at DATETIME NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  active_order_key BIGINT UNSIGNED GENERATED ALWAYS AS (IF(status IN ('PENDING','UNKNOWN','POSTED','PARTIALLY_REVERSED'), order_id, NULL)) STORED,
  UNIQUE KEY uq_guest_charges_number (charge_number),
  UNIQUE KEY uq_guest_charges_idempotency (idempotency_key),
  UNIQUE KEY uq_guest_charges_pms_tx (pms_transaction_id),
  UNIQUE KEY uq_guest_charges_one_active (active_order_key),
  KEY idx_guest_charges_order (order_id),
  KEY idx_guest_charges_status (status, created_at),
  KEY idx_guest_charges_folio (external_folio_id),
  KEY idx_guest_charges_room (room_number, created_at),
  CONSTRAINT fk_guest_charges_order FOREIGN KEY (order_id) REFERENCES orders (id),
  CONSTRAINT fk_guest_charges_user FOREIGN KEY (requested_by) REFERENCES users (id),
  CONSTRAINT chk_guest_charges_amount CHECK (amount > 0 AND reversed_amount >= 0 AND reversed_amount <= amount)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE refunds (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  refund_number VARCHAR(30) NOT NULL,
  order_id BIGINT UNSIGNED NOT NULL,
  refund_type ENUM('FULL','PARTIAL') NOT NULL,
  settlement_type ENUM('DIRECT_PAYMENT','ROOM_CHARGE') NOT NULL,
  amount DECIMAL(12,2) NOT NULL,
  reason VARCHAR(255) NOT NULL,
  status ENUM('REQUESTED','APPROVED','REJECTED','PROCESSED','FAILED') NOT NULL DEFAULT 'REQUESTED',
  restock TINYINT(1) NOT NULL DEFAULT 0,
  refund_method_id INT UNSIGNED NULL,
  payment_id BIGINT UNSIGNED NULL,
  guest_charge_id BIGINT UNSIGNED NULL,
  shift_id INT UNSIGNED NULL,
  external_reference VARCHAR(100) NULL,
  idempotency_key VARCHAR(100) NOT NULL,
  requested_by INT UNSIGNED NOT NULL,
  approved_by INT UNSIGNED NULL,
  approved_at DATETIME NULL,
  rejection_reason VARCHAR(255) NULL,
  processed_by INT UNSIGNED NULL,
  processed_at DATETIME NULL,
  failure_reason VARCHAR(255) NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_refunds_number (refund_number),
  UNIQUE KEY uq_refunds_idempotency (idempotency_key),
  KEY idx_refunds_order (order_id),
  KEY idx_refunds_status (status, created_at),
  CONSTRAINT fk_refunds_order FOREIGN KEY (order_id) REFERENCES orders (id),
  CONSTRAINT fk_refunds_method FOREIGN KEY (refund_method_id) REFERENCES payment_methods (id),
  CONSTRAINT fk_refunds_payment FOREIGN KEY (payment_id) REFERENCES payments (id),
  CONSTRAINT fk_refunds_guest_charge FOREIGN KEY (guest_charge_id) REFERENCES guest_charges (id),
  CONSTRAINT fk_refunds_shift FOREIGN KEY (shift_id) REFERENCES shifts (id),
  CONSTRAINT fk_refunds_requested_by FOREIGN KEY (requested_by) REFERENCES users (id),
  CONSTRAINT fk_refunds_approved_by FOREIGN KEY (approved_by) REFERENCES users (id),
  CONSTRAINT fk_refunds_processed_by FOREIGN KEY (processed_by) REFERENCES users (id),
  CONSTRAINT chk_refunds_amount CHECK (amount > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE refund_items (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  refund_id INT UNSIGNED NOT NULL,
  order_item_id BIGINT UNSIGNED NOT NULL,
  quantity DECIMAL(10,3) NOT NULL,
  amount DECIMAL(12,2) NOT NULL,
  restock TINYINT(1) NOT NULL DEFAULT 0,
  KEY idx_refund_items_refund (refund_id),
  KEY idx_refund_items_order_item (order_item_id),
  CONSTRAINT fk_refund_items_refund FOREIGN KEY (refund_id) REFERENCES refunds (id),
  CONSTRAINT fk_refund_items_order_item FOREIGN KEY (order_item_id) REFERENCES order_items (id),
  CONSTRAINT chk_refund_items_qty CHECK (quantity > 0 AND amount >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Receipts keep a JSON snapshot so reprints always match what was issued.
CREATE TABLE receipts (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  receipt_number VARCHAR(30) NOT NULL,
  order_id BIGINT UNSIGNED NOT NULL,
  refund_id INT UNSIGNED NULL,
  receipt_type ENUM('SALE','ROOM_CHARGE','REFUND') NOT NULL,
  snapshot JSON NOT NULL,
  print_count INT UNSIGNED NOT NULL DEFAULT 0,
  last_printed_at DATETIME NULL,
  generated_by INT UNSIGNED NOT NULL,
  generated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  sale_key BIGINT UNSIGNED GENERATED ALWAYS AS (IF(refund_id IS NULL, order_id, NULL)) STORED,
  UNIQUE KEY uq_receipts_number (receipt_number),
  UNIQUE KEY uq_receipts_one_sale_receipt (sale_key),
  UNIQUE KEY uq_receipts_refund (refund_id),
  KEY idx_receipts_order (order_id),
  KEY idx_receipts_generated (generated_at),
  CONSTRAINT fk_receipts_order FOREIGN KEY (order_id) REFERENCES orders (id),
  CONSTRAINT fk_receipts_refund FOREIGN KEY (refund_id) REFERENCES refunds (id),
  CONSTRAINT fk_receipts_user FOREIGN KEY (generated_by) REFERENCES users (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
